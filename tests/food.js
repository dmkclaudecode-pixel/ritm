// Проверка базы продуктов: фраза → ожидаемое блюдо (и, при необходимости, граммы)
const CASES = [
  ["съел гречку с курицей", "Гречка с курицей"], ["съела борщ со сметаной", "Борщ со сметаной"], ["поел куриный суп", "Куриный суп с лапшой"],
  ["съел 200 г лосося", "Лосось", 200], ["выпил капучино и съел круассан", "Капучино"], ["съел сникерс", "Сникерс"],
  ["выпил 2 бокала красного вина", "Вино красное"], ["позавтракал овсянкой на молоке", "Овсянка на молоке"], ["съел роллы", "Роллы"],
  ["выпил энергетик", "Энергетик"], ["съел плов", "Плов"], ["съел 3 яйца", "Яйцо"], ["выпил латте", "Латте"], ["съел пиццу пепперони", "Пицца пепперони"],
  ["съел творог 150 г", "Творог", 150], ["съел хачапури", "Хачапури"], ["выпил морс", "Морс"], ["съел шашлык", "Свинина"],
  ["выпил протеиновый коктейль", "Протеиновый коктейль"], ["съел пельмени", "Пельмени"], ["съел бутерброд с колбасой", "Бутерброд с колбасой"],
];
let bad = 0;
for(const [t, name, grams] of CASES){
  const r = RITM.parseFood(t); const hit = r.find(x => x.food === name);
  if(!hit || (grams && hit.grams !== grams)){ bad++; console.log(`ЕДА «${t}»: ждали ${name}${grams ? " " + grams + " г" : ""}, вышло ${JSON.stringify(r.map(x => x.food + " " + x.grams))}`); }
}
console.log(`Еда: ${CASES.length - bad} из ${CASES.length}` + (bad ? " (есть ошибки)" : ""));
if(bad) process.exitCode = 1;
