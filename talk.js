// Rhythm · разговор: по реплике, настроению и контексту беседы подбирает смысл хода (акт) и строит ответ.
// Правила: не повторяться, не задавать вопрос в каждой реплике, не радоваться грустному, тему держать до смены, при неясности уточнять.
(function(root){
"use strict";
const R = root.RITM = root.RITM || {};
const N = s => " " + String(s).toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я0-9?!. -]/g, " ").replace(/\s+/g, " ").trim() + " ";

// темы разговора: ключевые слова → название темы (для обращения «про работу», «про сон») и банк вопросов
const TOPICS = [
  {k:"work",   re:/ (работ|офис|начальник|коллег|проект|совещан|митинг|отчет|клиент|дедлайн|смен[аеуы]|задач)/, about:"работе",
    q:["Что на работе сейчас самое важное?", "Как с командой, всё ровно?", "Что в работе тебя сейчас больше всего забирает?"]},
  {k:"study",  re:/ (учеб|универ|институт|экзамен|сессия|лекци|курс|домашк|школ|зачет|диплом)/, about:"учёбе",
    q:["Что по учёбе сейчас горит?", "Когда ближайший экзамен или сдача?"]},
  {k:"family", re:/ (семь|мам[аеуы]|пап[аеуы]|родител|жен[аеуы]|муж[аеу]|сын|доч|ребен|дет[иеям]|брат|сестр|бабушк|дедушк)/, about:"семье",
    q:["Как у родных дела?", "Часто получается побыть с семьёй?"]},
  {k:"friends",re:/ (друг|друз|подруг|компани|встреч|тусовк|вечеринк)/, about:"друзьях",
    q:["Давно виделись с друзьями?", "С кем из близких хочется повидаться?"]},
  {k:"sleep",  re:/ (сон|спал|спать|выспал|бессонниц|засыпа|просыпа|ночь|ночью)/, about:"сне",
    q:["Во сколько обычно ложишься?", "Как сон в последние дни?"]},
  {k:"food",   re:/ (еда|поел|поела|ужин|обед|завтрак|готовил|перекус|голод|диет|вес)/, about:"еде",
    q:["Что сегодня ел?", "Хватает ли белка и воды сегодня?"]},
  {k:"sport",  re:/ (трениров|спорт|бег|пробежк|зал|качал|плаван|йог|растяжк|шаги)/, about:"тренировках",
    q:["Как ощущения после нагрузки?", "Что в тренировках получается лучше всего?"]},
  {k:"health", re:/ (здоровь|болит|болею|врач|таблетк|давление|температур|простуд|самочувств)/, about:"самочувствии",
    q:["Давно болит или только началось?", "Обращался к врачу?"]},
  {k:"money",  re:/ (деньг|зарплат|кредит|ипотек|долг|трат|налог|аренд)/, about:"деньгах",
    q:["Что в финансах больше всего беспокоит?"]},
  {k:"weekend",re:/ (выходн|отпуск|каникул|суббот|воскресень|праздник|путешеств|поездк)/, about:"отдыхе",
    q:["Что планируешь на отдых?", "Какой отдых тебе сейчас нужнее: активный или тихий?"]}
];
const ACK = /^ ?(ага|угу|ясно|понятно|ну да|да уж|так|окей|ок|ладно|хорошо|понял|поняла|ммм?|м+|ну|эх|ох|да)[!. ]*$/;
const WHATUP = / (как (ты|дела|жизнь)|что нового|как сам) /;
const AND_YOU = /^ ?(а ты|а у тебя|а вы|ты как)\??[!. ]*$/;
const ASK_ADVICE = / (что делать|посоветуй|подскажи|как быть|что посоветуешь|что мне делать|как справиться|как успокоиться|как взбодриться|как заставить себя) /;
const INVITE = /^ ?(расскажи( мне)?( что[- ]нибудь)?|давай (поговорим|поболтаем|пообщаемся)|поболтаем|поговорим|поговори со мной|развлеки меня)[!?. ]*$/;
const SELF_NEG = / (я (ничтожество|неудачник|неудачница|бесполезн|тупой|тупая|никчемн|слабак|ужасный человек|все порчу|всё порчу)|ничего не умею|ни на что не гожусь|я плохой|я плохая) /;
const BOT_Q = / (ты (умеешь|можешь|знаешь|помнишь|любишь|чувствуешь|думаешь|понимаешь)|как ты (думаешь|считаешь)|что ты думаешь|тебе (нравится|скучно|грустно|интересно)) /;
const EVENT = / (был[аи]?|ходил[аи]?|ездил[аи]?|пошел|пошла|сделал[аи]?|купил[аи]?|встретил[аи]?|видел[аи]?|получил[аи]?|начал[аи]?|закончил[аи]?|случил|произошл|сегодня|вчера|утром|вечером|на днях) /;

function topicOf(text){ const s = N(text); return TOPICS.find(t => t.re.test(s)) || null; }
const pick = (arr, ctx, rnd) => {
  const pool = ctx ? arr.filter(x => !ctx.said.includes(x)) : arr, src = pool.length ? pool : arr;
  const v = src[Math.floor((rnd ? rnd() : Math.random()) * src.length)]; if(ctx) ctx.fresh(v); return v;
};

// вопрос в каждой реплике утомляет: после вопроса бота следующий ход — без вопроса
function mayAsk(ctx){ const lb = ctx && ctx.last("bot"); return !(lb && lb.meta.asked); }

// главный вход: {text, mood, ctx, rnd} → {text, act, asked, topic}
function reply(o){
  const text = o.text || "", s = N(text), ctx = o.ctx, mood = o.mood || {}, rnd = o.rnd, D = R.dialog;
  const words = s.trim().split(" ").filter(Boolean).length, strong = (mood.intensity || 0) >= .35;
  const tp = topicOf(text), prevTopic = ctx && ctx.topic() ? ctx.topic() : null, topic = tp ? tp.k : prevTopic;
  const done = (act, out, asked) => ({text: out, act, asked: !!asked, topic: topic || null});
  const EMO_NEED = (mood.needs || [])[0];

  if(INVITE.test(s)) return done("invite", pick(["Давай. Можем начать с того, как прошёл день, или с того, что тебя сейчас занимает. С чего хочешь?", "С удовольствием. Как день сегодня: больше хорошего или тяжёлого?"], ctx, rnd), true);
  if(SELF_NEG.test(s)) return done("selfneg", pick(["Я слышу, как тебе сейчас тяжело. Одна неудача или тяжёлый день не делают человека плохим. Что именно случилось?", "Так про себя говорят, когда очень устают и расстраиваются. Это не приговор. Расскажешь, что произошло?", "Мне не нравится, как ты о себе говоришь: по данным, которые я вижу, ты многое делаешь. Что сейчас болит сильнее всего?"], ctx, rnd), true);
  if(AND_YOU.test(s)) return done("andyou", pick(["У меня всё ровно: я приложение, усталости не знаю. Мне интереснее, как у тебя.", "Спасибо, что спросил. У меня всё спокойно, а как ты?"], ctx, rnd), true);
  if(WHATUP.test(s) && words <= 5) return done("whatsup", pick(["Спасибо, всё в порядке. Как ты сегодня?", "У меня всё хорошо, я на связи. Как у тебя день?"], ctx, rnd), true);
  if(BOT_Q.test(s)) return done("botq", pick(["Я приложение с правилами и небольшой моделью, так что могу ошибаться. Но стараюсь понять, что тебе нужно. А ты что хотел узнать?", "Честно: я не человек и не чувствую, как ты, зато помню твои записи и учусь на них. Что тебя интересует?"], ctx, rnd), true);
  if(ASK_ADVICE.test(s)){
    const adv = {rest: "Начни с малого: стакан воды, десять минут без экрана и ранний отбой. Остальное подождёт.", support: "Давай по шагам. Сначала выдох: вдох на четыре счёта, выдох на шесть. Потом одно маленькое дело, которое точно получится.", activate: "Выбери самое лёгкое дело из плана и дай себе десять минут. Дальше обычно втягиваешься.", channel: "Возьми одну главную задачу и сделай её первой, пока есть запал."};
    return done("advice", adv[EMO_NEED] || "Подскажу, если расскажешь чуть подробнее: что сейчас мешает больше всего?", !adv[EMO_NEED]);
  }
  if(ACK.test(s)){
    if(prevTopic && mayAsk(ctx)){ const t = TOPICS.find(x => x.k === prevTopic); if(t) return done("ack", pick(t.q, ctx, rnd), true); }
    return done("ack", pick(["Я здесь, если захочешь продолжить.", "Хорошо. Скажи, когда будет что записать.", "Понимаю."], ctx, rnd), false);
  }
  // сильная эмоция: эмпатия + (изредка) мягкий вопрос
  if(strong && D){
    let t = D.compose({mood}, ctx, rnd);
    for(let i = 0; i < 6 && !mayAsk(ctx) && /\?\s*$/.test(t); i++) t = D.compose({mood}, ctx, rnd);   // после вопроса бота — реплика без вопроса
    if(!mayAsk(ctx) && /\?\s*$/.test(t)) t = t.replace(/[^.!]*\?\s*$/, "").trim() || t;
    return done("mood", t, /\?\s*$/.test(t));
  }
  // рассказ о событии: признаём, потом любопытство к чувствам или теме
  if(words >= 4 && EVENT.test(s)){
    const a = pick(["Понятно, спасибо, что рассказал.", "Ясно, звучит как насыщенный день.", "Услышал тебя.", "Интересно."], ctx, rnd);
    if(mayAsk(ctx)){
      const q = tp ? pick(tp.q, ctx, rnd) : pick(["Как ты сам к этому относишься?", "И как тебе это?", "Что в этом было главным для тебя?"], ctx, rnd);
      return done("event", a + " " + q, true);
    }
    return done("event", a, false);
  }
  // тема есть, но без события: коротко поддерживаем и спрашиваем о теме
  if(tp && mayAsk(ctx) && words >= 2) return done("topic", `Давай про ${tp.about} подробнее. ` + pick(tp.q, ctx, rnd), true);
  // неясно: честно уточняем
  if(words >= 2){
    const q = mayAsk(ctx) ? pick(["Я не уверен, что понял. Это про дела, самочувствие или просто хочется поговорить?", "Расскажи чуть подробнее, чтобы я понял правильно.", "Это про что-то, что мне записать, или просто делишься?"], ctx, rnd) : pick(["Продолжай, я слушаю.", "Я здесь."], ctx, rnd);
    return done("clarify", q, /\?$/.test(q));
  }
  return done("short", pick(["Слушаю.", "Я здесь.", "Продолжай."], ctx, rnd), false);
}

// реплики, которые точно обращены к боту или о самом человеке, а не про дела: их разбираем до поиска занятий
function direct(text){ const s = N(text); return INVITE.test(s) || SELF_NEG.test(s) || BOT_Q.test(s) || AND_YOU.test(s); }
R.talk = {reply, topicOf, direct, TOPICS};
if(typeof module !== "undefined" && module.exports) module.exports = R.talk;
})(typeof window !== "undefined" ? window : globalThis);
