// Разметка реплики бота на «ходы»: открытие (open), содержание (body), закрытие (close). Один ход на слот.
// Используется для обучения планировщика реакции и для оценки. Чистые функции, регулярки по эталонным репликам.
const N = s => " " + String(s).toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я0-9?!.,-]/g, " ").replace(/\s+/g, " ").trim() + " ";
function split(text){ const parts = String(text).split(/(?<=[.!?])\s+/).filter(Boolean); return parts; }
const OPEN = [
  ["praise",   /^ (поздравля|ура|здорово|отлично|класс|круто|вот это|ого|супер|молодец|рад |приятно|прекрасно|красота|замечательно)/],
  ["empathy",  /^ (мне жаль|жаль|понимаю|сочувству|звучит (тяжело|выматывающе|непросто)|тяжело|непросто|бывает|знаком|это (тяжело|обидно|мучительно|неприятно)|обидно|неприятно|слышу|бесит|страшно|грустно|нормально волноваться)/],
  ["ack",      /^ (хорошо|ладно|понял|понятно|ясно|принято|договорились|окей|ок |записал|запомню|запомнил|исправил|убрал|тогда|значит)/],
];
const BODY = [
  ["doctor",   /(врач|доктор|ветеринар|стоматолог|психолог|линия доверия|112|8-800)/],
  ["breath",   /(вдох|выдох|дыши|дыхани)/],
  ["rest",     /(отдых|отдохни|лечь|пораньше|выспа|сон |сна |спать|без подвигов|полегче|вода|воды|тёплого питья|растяжк|передышк|тише|покой)/],
  ["activity", /(прогулк|пройд|зарядк|тренировк|разомни|выйди|на воздух|музык|чай|плед|кино|сериал|книг)/],
  ["plan",     /(план|напомин|таймер|расписан|список|выпиши|на бумаг|привычк)/],
  ["info",     /(для тебя|это (мало|много|нормально)|маловато|многовато|нормально, этого|прогресс|рекорд|вдвое|хватит)/],
];
const CLOSE = [
  ["offer",    /(поставить|добавить|хочешь,? (чтобы|помогу|поставлю|подскажу|расскажу)|составим|подсказать|помочь|договорились\?|подойд[её]т\?|включить|убрать|поменять|напомнить)[^?]*\?\s*$/],
  ["cause",    /(что (случилось|именно|вымотало|тревожит|помешало|сделало|бесит|крутится|стало|за )|почему|из-за чего|что из этого)[^?]*\?\s*$/],
  ["feeling",  /(как (ты|себя|ощущения|сейчас|самочувствие|день|спал)|что на душе|тяжело или|как оно)[^?]*\?\s*$/],
  ["amount",   /(сколько|давно|как долго|во сколько|когда|как часто|на сколько)[^?]*\?\s*$/],
  ["detail",   /(расскажи|расскажешь|что смотрел|что делал|что ел|что за|куда едешь|кто она|чем занимаешься|поделишься|покажешь|что-нибудь запомнилось)[^?]*\?\s*$/],
  ["next",     /(планируешь|будем|дальше|что-то планируешь|что берём|что возьмёшь|выйдешь|отметишь|отметим|планы)[^?]*\?\s*$/],
];
function moves(text){
  const parts = split(text), res = {open: "none", body: "none", close: "none"};
  const first = N(parts[0] || "");
  for(const [k, re] of OPEN) if(re.test(first)){ res.open = k; break; }
  const mid = N(parts.slice(0, -1).join(" ") || parts[0] || ""), allBody = N(text.replace(/[^.!?]*\?\s*$/, ""));
  for(const [k, re] of BODY) if(re.test(allBody)){ res.body = k; break; }
  const last = String(text).match(/[^.!?]*\?\s*$/);
  if(last){ const q = N(last[0]).trim(); res.close = "ask"; for(const [k, re] of CLOSE) if(re.test(" " + q)){ res.close = k; break; } }
  return res;
}
module.exports = {moves, OPEN, BODY, CLOSE, N, split};
