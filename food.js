      const m = /(\d+(?:[.,]\d+)?)\s*(кг|г|гр|грамм\w*|мл|л|шт\w*|кусоч\w*|ломт\w*|ложк\w*|л\.|стакан\w*|порци\w*|тарел\w*|банк\w*|чашк\w*|бутыл\w*|кружк\w*)?/.exec(part);
      if(m){ qty = parseFloat(m[1].replace(",", ".")); unit = m[2] || ""; }
