// Суточная норма калорий: Миффлин — Сан Жеор × коэффициент активности. Это оценка поддержания веса, не диета.
RITM.calorieTarget = function(s, steps){
  if(!s.weight || !s.height || !s.age || !s.sex) return null;
  const bmr = 10 * s.weight + 6.25 * s.height - 5 * s.age + (s.sex === "m" ? 5 : -161);
  const k = steps >= 12000 ? 1.6 : steps >= 8000 ? 1.5 : steps >= 5000 ? 1.4 : 1.3;
  const kcal = Math.round(bmr * k / 50) * 50, protein = s.proteinGoal || Math.round(s.weight * 1.4);
  const fat = Math.round(kcal * 0.28 / 9), carbs = Math.max(0, Math.round((kcal - protein * 4 - fat * 9) / 4));
  return {kcal, protein, fat, carbs, bmr: Math.round(bmr)};
};
