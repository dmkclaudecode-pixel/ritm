      let grams;
      if(/^(г|гр|грамм)/.test(unit)) grams = qty;
      else if(unit === "кг") grams = qty * 1000;
      else if(unit === "мл") grams = qty;
      else if(unit === "л") grams = qty * 1000;
      else if(/^ложк/.test(unit)) grams = qty * (fd.sp || 15);
