function analyze(text){
  const s = N(text);
  const out = {s, words: words(s), crisis:false, states:[], small:[], correction:null, question:false, topics:[]};
  if(CRISIS_P.test(s)){ out.crisis = true; return out; }
  for(const st of STATES) if(st.re.test(s)){
    const x = {k:st.k};
    if(st.k === "pain"){ const p = PAIN_PLACE.find(([w]) => s.includes(w)); x.place = p ? p[1] : "other"; }
    // «не устал» и «не болит» — не жалоба
    if(new RegExp(" (не|ничего не|вовсе не|совсем не) " + st.re.source.replace(/^ /, "")).test(s) && !new RegExp(st.re.source).test(s.replace(/ (не|ничего не|вовсе не|совсем не) \S+/g, " "))) continue;
    out.states.push(x);
  }
  // «кот заболел», «у мамы болит голова» — не про самого человека: состояния не ставим
  out.subj3 = THIRD.test(s) && !FIRST.test(s);
  if(out.states.length && out.subj3){ out.states = []; out.third = true; }
  if(out.states.some(x=>x.k==="good") && out.states.length > 1) out.states = out.states.filter(x=>x.k!=="good");
  for(const [k, re] of SMALL) if(re.test(s)) out.small.push(k);
  out.correction = correction(s);
  if(META_TOO_EARLY.test(s)) out.meta = "tooEarly"; else if(META_DONT_CHANGE.test(s)) out.meta = "dontChange";
  out.notMine = !/\d/.test(s) && NOT_MINE.some(re => re.test(s));
  out.conversational = CONVERSATIONAL.test(s) && !/\d/.test(s) && words(s) >= 4;
  out.question = QUESTION.test(s.replace(/ (потому что|так что|то что|за то что|раз что|что-то|что-нибудь|как-то|как будто|когда-то|как обычно|как всегда|как раз) /g, " _ "));
  for(const [k, re] of ASK_TOPICS) if(re.test(s)) out.topics.push(k);
  return out;
}

R.analyze = analyze;
