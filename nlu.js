// ---------- поправки к последним записям ----------
function correction(s){
  // «удали последнее», «отмени запись», «это ошибка»
  if(/ (удали|отмени|убери|сотри|откати)[а-я]* (последн|это|эту|запись|записи|что записал|мою запись)| это ошибка | случайно отправил | не то записал /.test(s) || /^ (отмена|отмени|удали) (последн[а-я]*|это) $/.test(s)) return {op:"undo"};
  // «это было вчера», «это вчера было»
  if(/ (это|было|это было|все это было|всё это было) (вчера|позавчера)| (вчера|позавчера) (это )?было /.test(s) && words(s) <= 6) return {op:"day", offset: / позавчера /.test(s) ? -2 : -1};
  // «это было в 18:30», «время 18:30», «не в 9, а в 10»
  let m = / (?:не в \d{1,2}(?:[:.]\d{2})?,? ?а )?в (\d{1,2})(?:[:.](\d{2}))? /.exec(s);
  if(m && (/ (это было|было в|на самом деле в|не в \d)/.test(s)) && words(s) <= 8) return {op:"time", time: String(m[1]).padStart(2,"0") + ":" + String(m[2]||"00").padStart(2,"0")};
  // «не 30, а 45 минут», «было 45 минут», «исправь на 45», «на самом деле 2 стакана»
  m = / не (\d+(?:[.,]\d+)?)\s*[а-я]*,? ?а (\d+(?:[.,]\d+)?)\s*([а-я]*)/.exec(s) || / (?:исправь|поправь|измени|поменяй)[а-я]* на (\d+(?:[.,]\d+)?)\s*([а-я]*)/.exec(s) || / (?:на самом деле|вообще-то|было) (\d+(?:[.,]\d+)?)\s*([а-я]*)/.exec(s);
  if(m && words(s) <= 9){ const n = m.length === 4 ? m[2] : m[1], unit = m.length === 4 ? m[3] : m[2]; return {op:"amount", n:parseFloat(String(n).replace(",",".")), unit:unit||""}; }
  // «не бег, а ходьба», «это была не силовая, а йога»
  m = / (?:это был[аио]? )?не ([а-я ]+?),? а ([а-я ]+) $/.exec(s);
  if(m && words(s) <= 8){ const t = R.guessType(m[2]); if(t) return {op:"type", type:t, what:m[2].trim()}; }
  // «нет, это было не то» без деталей
  if(/^ (нет|не так|неправильно|ошибся|ошиблась|не то|не верно|неверно) /.test(s) && words(s) <= 4) return {op:"what"};
  return null;
}

